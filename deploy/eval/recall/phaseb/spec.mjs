// unknown 题的 mustNot 就是「具体值」保险：出现就失败，不管前面用什么说法引出来。
// 不判的题目：c7-2（翻原文标头，格式题，没有回答可判）、c9-4（只考记忆不再召回，帐本原文仍在，回答是什么都合理）、
