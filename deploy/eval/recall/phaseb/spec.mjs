// 判定一份回答（text 已转简体）。回传 { auto: boolean, failed: [说明…], human: string|null }
export function judge(id, text) {
	const spec = SPEC[id];
	const failed = [];
	for (const rx of spec.must ?? []) if (!rx.test(text)) failed.push('缺 ' + rx);
	for (const rx of spec.mustNot ?? []) if (rx.test(text)) failed.push('不该出现 ' + rx);
	if (spec.unknown && !UNKNOWN.test(text)) failed.push('没有表示不知道／没有纪录');
	if (spec.unknown && GUESS.test(text)) failed.push('说不知道却又猜了一个答案 ' + GUESS);
	return { auto: failed.length === 0, failed, human: spec.human ?? null };
}
