export const UNKNOWN = /不知道|不清楚|没印象|没有印象|不记得|记不起|不确定|没听|没看到|没有看到|查不到|找不到|没有(相关|这方面|纪录|记录)|没说过|没提过|没(有)?人(说|提)|想不起/;

// 「说不知道、却又猜了一个答案」：不知道类的题（unknown）出现这些说法一律不过——
//   猜测：应该是／可能是／大概在／也许／我猜…＋内容（"我不知道生日，但应该是四月"）
//   传闻：听说／据说／有人说／印象中／我记得／隐约…（"我不知道，听说是四月"、"没印象，有人说他去日本了"）
// 「可能没说过」「应该没有记录」「没听说过」「有没有人说过」「印象中没有」猜的是「没有」本身，不算（后面接 没／不／还／无，或前面有 没／未／不／无 的放过）。
// 这条正则补不完所有说法，所以 unknown 类的题还有第二道保险：回答里只要出现该题 mustNot 列出的具体值（含 WORLD 世界里的事实、PLACES 地名、日期），不管前面怎么引出来都判失败；再加人工抽查（见 PLAN）。
const NEG = '[没未不无]';
export const GUESS = new RegExp(
	[
		'(?:应该|可能|大概|也许|或许|估计|多半|八成|好像|似乎|说不定)(?:就)?(?:是|为|在|会|有|叫|去|住|喜欢|养)(?![没不还])',
		'我猜(?!不)',
		'猜(?:是|她|他|你)',
		`(?<!${NEG}[^，。！？\\n]{0,3})(?:听说|据说|听人说|听闻|听别人说|传闻)(?![^，。！？\\n]{0,2}${NEG})`,
		`(?<!${NEG}[^，。！？\\n]{0,3})有(?:人|个人|些人|群友|朋友|同事)(?:说|讲|提过|提到|跟我说|告诉我)(?![^，。！？\\n]{0,2}${NEG})`,
		'印象(?:中|里|当中)(?![^，。！？\\n]{0,3}[没不无])',
		'我记得(?![不没无])',
		'记得(?:好像|似乎|是)(?![没不无])',
		'隐约',
		'依稀',
		'好像听',
	].join('|'),
);

